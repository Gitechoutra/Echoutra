// ── Chart data generator ────────────────────────────────────────────────────
export function generateChartData(days = 30, basePrice = 150, trend = 0.3) {
  const data = [];
  let price = basePrice;
  const now = new Date();
  for (let i = days; i >= 0; i--) {
    const date = new Date(now);
    date.setDate(date.getDate() - i);
    const vol = (Math.random() - 0.5) * 5;
    price = Math.max(price + trend + vol, basePrice * 0.5);
    const open = price + (Math.random() - 0.5) * 2;
    data.push({
      date: date.toLocaleDateString("en-US", {
        month: "short",
        day: "numeric",
      }),
      close: parseFloat(price.toFixed(2)),
      open: parseFloat(open.toFixed(2)),
      high: parseFloat((Math.max(price, open) + Math.random() * 3).toFixed(2)),
      low: parseFloat((Math.min(price, open) - Math.random() * 3).toFixed(2)),
      volume: Math.floor(Math.random() * 50000000 + 10000000),
    });
  }
  return data;
}

